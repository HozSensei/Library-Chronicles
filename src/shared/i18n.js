/**
 * i18n léger FR/EN — pas de vue-i18n.
 * Locale courante mutable (stores / UI) + t() pur pour scripts/tests.
 */

/** @typedef {'fr'|'en'} Locale */

export const LOCALES = Object.freeze(['fr', 'en']);
export const DEFAULT_LOCALE = 'fr';

/** @type {Locale} */
let currentLocale = DEFAULT_LOCALE;

/**
 * @param {unknown} value
 * @returns {Locale}
 */
export function normalizeLocale(value) {
  const v = String(value || '')
    .trim()
    .toLowerCase();
  if (v === 'en' || v.startsWith('en-') || v === 'english' || v === 'anglais') {
    return 'en';
  }
  return 'fr';
}

/** @returns {Locale} */
export function getLocale() {
  return currentLocale;
}

/**
 * @param {unknown} value
 * @returns {Locale}
 */
export function setLocale(value) {
  currentLocale = normalizeLocale(value);
  return currentLocale;
}

/**
 * @param {Record<string, unknown>} dict
 * @param {string} path
 */
function lookup(dict, path) {
  const parts = String(path || '').split('.');
  let cur = dict;
  for (const part of parts) {
    if (cur == null || typeof cur !== 'object') return undefined;
    cur = cur[part];
  }
  return typeof cur === 'string' ? cur : undefined;
}

/**
 * Remplace {name} dans une chaîne.
 * @param {string} template
 * @param {Record<string, string|number>|null|undefined} params
 */
export function interpolate(template, params) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key) =>
    params[key] != null ? String(params[key]) : `{${key}}`,
  );
}

/**
 * @param {string} key
 * @param {Record<string, string|number>|null} [params]
 * @param {Locale|string} [locale]
 * @returns {string}
 */
export function t(key, params = null, locale = currentLocale) {
  const loc = normalizeLocale(locale);
  const primary = lookup(MESSAGES[loc], key);
  if (primary != null) return interpolate(primary, params);
  const fallback = lookup(MESSAGES[DEFAULT_LOCALE], key);
  if (fallback != null) return interpolate(fallback, params);
  return String(key);
}

/** Labels d’accent localisés (ids stables). */
export function accentLabelI18n(id, locale = currentLocale) {
  const aid = String(id || '').toLowerCase();
  return t(`accent.${aid}`, null, locale);
}

